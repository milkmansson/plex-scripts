"""completion: print a shell completion script for plextool."""

from __future__ import annotations

import argparse

from .common import add_command

SHELLS = ("bash", "zsh")


def walk(parser: argparse.ArgumentParser, path: tuple[str, ...] = ()) -> dict:
    """{path: {'subs': [...], 'opts': [...], 'value_opts': [...], 'choices': {option: [...]}}} for a parser tree."""
    info = {"subs": [], "opts": [], "value_opts": [], "choices": {}}
    found = {path: info}
    for action in parser._actions:
        if isinstance(action, argparse._SubParsersAction):
            for name, sub in action.choices.items():
                info["subs"].append(name)
                found.update(walk(sub, (*path, name)))
            continue
        for option in action.option_strings:
            if not option.startswith("-"):
                continue
            info["opts"].append(option)
            if action.nargs != 0:
                info["value_opts"].append(option)
                if action.choices:
                    info["choices"][option] = [str(c) for c in action.choices]
    return found


def _case(name: str, found: dict, field: str) -> str:
    lines = [f"_plextool_{name}() {{", '  case "$1" in']
    for path, info in found.items():
        words = info[field]
        if words:
            lines.append(f'    "{" ".join(path)}") echo "{" ".join(words)}" ;;')
    lines += ["  esac", "}"]
    return "\n".join(lines)


def _choices_case(found: dict) -> str:
    lines = ["_plextool_choices() {", '  case "$1|$2" in']
    for path, info in found.items():
        for option, values in info["choices"].items():
            lines.append(f'    "{" ".join(path)}|{option}") echo "{" ".join(values)}" ;;')
    lines += ["  esac", "}"]
    return "\n".join(lines)


def script(shell: str, parser: argparse.ArgumentParser) -> str:
    """The completion script for `shell`, built from the current commands and options."""
    found = walk(parser)
    head = ["# plextool completion for " + shell + ". Generated by 'plextool completion " + shell + "'."]
    if shell == "zsh":
        head.append("autoload -U +X bashcompinit && bashcompinit")
    parts = [
        "\n".join(head),
        _case("subs", found, "subs"),
        _case("opts", found, "opts"),
        _case("valopts", found, "value_opts"),
        _choices_case(found),
        r'''_plextool() {
  local cur="${COMP_WORDS[COMP_CWORD]}" prev="" path="" word skip=0 i choices
  [ "$COMP_CWORD" -gt 0 ] && prev="${COMP_WORDS[COMP_CWORD-1]}"
  for ((i = 1; i < COMP_CWORD; i++)); do
    word="${COMP_WORDS[i]}"
    if [ "$skip" -eq 1 ]; then skip=0; continue; fi
    case "$word" in
      -*) case " $(_plextool_valopts "$path") " in *" $word "*) skip=1 ;; esac ;;
      *) case " $(_plextool_subs "$path") " in *" $word "*) path="${path:+$path }$word" ;; esac ;;
    esac
  done
  COMPREPLY=()
  choices="$(_plextool_choices "$path" "$prev")"
  if [ -n "$choices" ]; then
    COMPREPLY=($(compgen -W "$choices" -- "$cur"))
  elif case " $(_plextool_valopts "$path") " in *" $prev "*) true ;; *) false ;; esac; then
    return 0   # the value of an option: leave it to the shell (file names and so on)
  elif [[ "$cur" == -* ]]; then
    COMPREPLY=($(compgen -W "$(_plextool_opts "$path")" -- "$cur"))
  else
    COMPREPLY=($(compgen -W "$(_plextool_subs "$path")" -- "$cur"))
  fi
}
complete -o default -F _plextool plextool''',
    ]
    return "\n\n".join(parts) + "\n"


def add_parser(subparsers) -> None:
    parser = add_command(
        subparsers, 'completion',
        'print a shell completion script (bash, zsh)',
        "Prints a script that completes plextool's commands, subcommands, options and fixed choices when Tab is "
        "pressed. It is built from the commands as they are now, so it never lags behind. Load it for the current "
        "shell with eval, or save it where the shell reads completions.",
        ['eval "$(plextool completion bash)"',
         'plextool completion bash > ~/.local/share/bash-completion/completions/plextool',
         'eval "$(plextool completion zsh)"   # in ~/.zshrc'])
    parser.add_argument("shell", choices=SHELLS, help="the shell to print the script for")
    parser.set_defaults(run=run)


def run(args: argparse.Namespace) -> int:
    from .cli import build_parser  # imported here because cli imports this module
    print(script(args.shell, build_parser()), end="")
    return 0
